"""
ASE (hapmixQTL) validation harness -- tiered.

The existing hapmixQTL test suite (tests/test_hapmixqtl.py, ~35 tests) is almost
entirely INTERNAL CONSISTENCY ("does the code compute the formula we wrote") plus
"can it recover a planted causal variant". Neither kind of test can detect an
invalid error rate. This harness supplies the missing evidence.

Three structural facts about the implementation motivate the design:

  F1 (tau).  `tau_mode='zero'` WAS the default in map_nominal/map_cis when this
      harness was written (it is 'estimate' now, because of Tier 0), so the
      weights are w_i = 1/v_inf_i. Combined with the known-variance GLS SE
      (Var(beta) = 1/xx, no estimated dispersion), the model asserts that Gibbs
      inferential variance is the ONLY source of error variance. Any additional
      biological variance is unmodelled -> SE too small -> anticonservative.

  F2 (Cat).  compute_summaries_from_gibbs returns the a-t inferential covariance
      and read_hapmixqtl_inputs accepts a cat_bed, but calculate_hapmixqtl_nominal
      combines the two channels by SCALAR inverse-variance meta-analysis, which
      assumes independence. a and t are both functions of the same Gibbs draws,
      so Cov != 0 in general and the combined SE is missing a 2*w_a*w_t*Cov term.
      Tier 0b MEASURED this and retired it: the slope estimators are uncorrelated
      even at rho = 0.9, because s is orthogonal to g/2 under random phase, so
      ignoring Cat is correct (hapmixqtl.py module docstring).

  F3 (dof). p-values are computed with get_t_pval(tstat, N-2-n_cov), i.e. a
      t-reference for what is by construction a known-variance z-statistic. Minor
      and conservative at large N; included here only so it is not confounded in.

Tiers
-----
  Tier 0  Null calibration. Factorial sweep over (biological variance, a-t
          inferential correlation) x (tau_mode). Reports realized type-I error at
          alpha = 0.05 / 0.01 / 1e-3, KS uniformity, lambda_GC. The cell with
          bio=0, rho=0 is the CONTROL where the model is exactly true; it must
          be nominal or the harness itself is wrong.
  Tier 1  CI coverage of a known log aFC (the sharpest probe of whether the
          inferential uncertainty propagates into beta_se correctly).
  Tier 2  Power vs total-only at MATCHED EMPIRICAL type-I error (not a matched
          nominal threshold -- an anticonservative method always "wins" on
          nominal, so that comparison is meaningless).
  Tier 3  Semisynthetic: simulate allele-level counts -> Gibbs draws ->
          compute_summaries_from_gibbs, so Va/Vt/Cat and the kappa pseudocount
          behaviour are generated by the real code path rather than assumed.

Run:  python tests/ase_validation.py --out results.json
"""

